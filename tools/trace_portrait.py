"""Trace the close-up of Capri's face (reference/capri-face-big.png) into
vector art for her portrait: the anime-style cut-in she pops up for big
moments, and the avatar in her chat header.

Like trace_art.py, every color region becomes a path and the hair glitter is
lifted out of the frame as an alpha mask. The eyes and the zigzag mouth are
painted over with ink and measured instead, so the portrait can draw them
live: blink, look around, talk.

usage: py tools/trace_portrait.py
"""

import json

import cv2
import numpy as np
from PIL import Image

import trace_art as T

SRC = T.ROOT / 'reference' / 'capri-face-big.png'
OUT = T.ROOT / 'src' / 'renderer' / 'portrait-art.js'
CROP = (300, 30, 800, 400)  # x0, y0, x1, y1 in the frame

# Measured on the frame (see the README): each ring as an ellipse (center,
# outer radii, rotation, thickness), the iris and the white pupil as circles.
EYES = [
    {'ring': (482.7, 218.5, 28.0, 29.2, 1.5), 'thick': 4.0, 'iris': (481.9, 220.0, 15.0), 'white': (482.7, 220.3, 6.2)},
    {'ring': (573.3, 271.9, 19.0, 25.0, 45.7), 'thick': 3.0, 'iris': (571.6, 273.1, 11.5), 'white': (570.9, 272.7, 4.5)},
]
MOUTH = [(452, 261), (471, 286), (477, 279), (489, 295), (494, 290), (521, 322)]


def main():
    frame = np.array(Image.open(SRC).convert('RGB')).astype(int)
    x0, y0, x1, y1 = CROP
    img = frame[y0:y1, x0:x1]
    R, G, B = (img[..., i] for i in range(3))
    k3 = np.ones((3, 3), np.uint8)
    shape = R.shape

    pink = (R > 150) & (G < 140) & (R > G + 80) & (R > B + 20)
    glitter = (R > 200) & (G > 140) & (B > 150)
    green = (G > 170) & (R < 120) & (G > B + 40)
    purple = (B > 110) & (B > R - 10) & (G < 90) & (R > 60)
    black = (R < 45) & (G < 35) & (B < 60)

    # Hair is pink plus the glitter inside it. The clouds are white too, so
    # glitter only counts inside the closed outline of the pink.
    hull = cv2.morphologyEx(pink.astype(np.uint8), cv2.MORPH_CLOSE, np.ones((11, 11), np.uint8)) > 0
    glitter &= hull
    hair = cv2.morphologyEx((pink | glitter).astype(np.uint8), cv2.MORPH_CLOSE, np.ones((5, 5), np.uint8)) > 0
    hair &= ~black

    # The eyes and mouth are drawn live: ink them over.
    live = np.zeros(shape, np.uint8)
    for eye in EYES:
        cx, cy, rx, ry, rot = eye['ring']
        cv2.ellipse(live, (round(cx - x0), round(cy - y0)), (round(rx + 1.5), round(ry + 1.5)), rot, 0, 360, 1, -1)
    mouth = [(x - x0, y - y0) for x, y in MOUTH]
    cv2.polylines(live, [np.array(mouth, np.int32)], False, 1, 5)
    live = live > 0

    silhouette = hair | green | purple | black | live
    silhouette = cv2.morphologyEx(silhouette.astype(np.uint8), cv2.MORPH_CLOSE, k3) > 0
    silhouette = T.drop_specks(silhouette, 12)
    layers = {
        'purple': (cv2.dilate(purple.astype(np.uint8), k3) > 0) & silhouette & ~live,
        'pink': hair & silhouette & ~live,
        'green': green & silhouette & ~live,
    }

    sparkle = np.clip((G - 14) / 230, 0, 1) * layers['pink']
    alpha = (sparkle * 255).round().astype(np.uint8)
    rgba = np.dstack([np.full_like(alpha, 255)] * 3 + [alpha])

    origin = np.zeros(2)
    rel = lambda x, y: [round(float(x - x0), 2), round(float(y - y0), 2)]
    art = {
        'width': x1 - x0,
        'height': y1 - y0,
        'base': T.path_data(silhouette, origin),
        **{k: T.path_data(v, origin) for k, v in layers.items()},
        'glitter': T.png_data_url(rgba),
        'eyes': [
            {
                'ring': [*rel(*e['ring'][:2]), e['ring'][2], e['ring'][3], e['ring'][4]],
                'thick': e['thick'],
                'iris': [*rel(*e['iris'][:2]), e['iris'][2]],
                'white': [*rel(*e['white'][:2]), e['white'][2]],
            }
            for e in EYES
        ],
        'mouth': [rel(x, y) for x, y in MOUTH],
    }
    OUT.write_text(
        '// Generated by tools/trace_portrait.py from the face close-up. Do not edit by hand.\n'
        'window.Capri = window.Capri || {};\n'
        f'window.Capri.PORTRAIT = {json.dumps(art, separators=(",", ":"))};\n',
        encoding='utf-8',
    )
    print(f'{OUT.relative_to(T.ROOT)}: {art["width"]}x{art["height"]}, {OUT.stat().st_size / 1024:.0f} KB')


if __name__ == '__main__':
    main()
